/**
 * Expo config plugin (Android): a Tailscale name the phone's own resolver can't find is asked of Tailscale's DNS.
 *
 * A server on a tailnet has a `*.ts.net` name that only Tailscale's DNS (MagicDNS, 100.100.100.100) knows. On some
 * phones the system's resolver doesn't send the app's lookups there (a Private DNS provider set in the phone's
 * settings answers them instead, for one) and they fail at once with "Unable to resolve host", while a browser, with
 * its own DNS client, opens the same address. React Native's fetch and WebSocket both take their OkHttp client from
 * `OkHttpClientProvider`, so this plugin gives it a factory whose client resolves with `TailnetDns`: the system first,
 * and only for a `*.ts.net` name it couldn't find, one A and one AAAA question to 100.100.100.100 over UDP (which
 * reaches Tailscale only while its VPN carries this app). Answers are kept for a minute.
 */
const fs = require("node:fs");
const path = require("node:path");
const { withDangerousMod, withMainApplication } = require("expo/config-plugins");

const MARK = "// agentes: tailnet names through Tailscale's DNS (plugins/with-tailnet-dns.js)";

const kotlinSource = (pkg) => `package ${pkg}

import android.content.Context
import com.facebook.react.modules.network.OkHttpClientFactory
import com.facebook.react.modules.network.OkHttpClientProvider
import java.io.ByteArrayOutputStream
import java.net.DatagramPacket
import java.net.DatagramSocket
import java.net.InetAddress
import java.net.UnknownHostException
import java.util.concurrent.ConcurrentHashMap
import kotlin.random.Random
import okhttp3.Dns
import okhttp3.OkHttpClient

/** Generated by plugins/with-tailnet-dns.js: what it does and why is written there. */
object TailnetDns : Dns {
  private const val MAGIC_DNS = "100.100.100.100"
  private const val TIMEOUT_MS = 2_000
  private const val KEEP_MS = 60_000L
  private const val TYPE_A = 1
  private const val TYPE_AAAA = 28
  private val kept = ConcurrentHashMap<String, Pair<Long, List<InetAddress>>>()

  fun isTailnet(host: String): Boolean = host.lowercase().trimEnd('.').endsWith(".ts.net")

  override fun lookup(hostname: String): List<InetAddress> {
    try {
      return Dns.SYSTEM.lookup(hostname)
    } catch (e: UnknownHostException) {
      if (!isTailnet(hostname)) throw e
      val now = System.currentTimeMillis()
      kept[hostname]?.let { (at, found) -> if (now - at < KEEP_MS) return found }
      val found = ask(hostname, TYPE_A) + ask(hostname, TYPE_AAAA)
      if (found.isEmpty()) {
        val error = UnknownHostException("$hostname: not found by the phone's DNS nor by Tailscale's ($MAGIC_DNS)")
        error.initCause(e)
        throw error
      }
      kept[hostname] = now to found
      return found
    }
  }

  private fun ask(host: String, type: Int): List<InetAddress> =
    try {
      DatagramSocket().use { socket ->
        socket.soTimeout = TIMEOUT_MS
        val id = Random.nextInt(0, 0x10000)
        val question = question(host, id, type)
        socket.send(DatagramPacket(question, question.size, InetAddress.getByName(MAGIC_DNS), 53))
        val buffer = ByteArray(1500)
        val packet = DatagramPacket(buffer, buffer.size)
        socket.receive(packet)
        answers(host, buffer, packet.length, id)
      }
    } catch (e: Exception) {
      emptyList()
    }

  private fun question(host: String, id: Int, type: Int): ByteArray {
    val out = ByteArrayOutputStream()
    out.write(id shr 8)
    out.write(id and 0xff)
    out.write(0x01) // recursion desired
    out.write(0x00)
    out.write(0x00) // one question
    out.write(0x01)
    repeat(6) { out.write(0x00) } // no answer, authority or additional records
    for (label in host.trimEnd('.').split('.')) {
      val bytes = label.toByteArray(Charsets.US_ASCII)
      out.write(bytes.size)
      out.write(bytes)
    }
    out.write(0x00)
    out.write(type shr 8)
    out.write(type and 0xff)
    out.write(0x00) // class IN
    out.write(0x01)
    return out.toByteArray()
  }

  private fun answers(host: String, b: ByteArray, length: Int, id: Int): List<InetAddress> {
    fun u16(at: Int): Int = ((b[at].toInt() and 0xff) shl 8) or (b[at + 1].toInt() and 0xff)
    if (length < 12 || u16(0) != id || (u16(2) and 0x000f) != 0) return emptyList()
    var at = 12
    fun skipName() {
      while (at < length) {
        val size = b[at].toInt() and 0xff
        if (size == 0) {
          at += 1
          return
        }
        if ((size and 0xc0) == 0xc0) {
          at += 2
          return
        }
        at += size + 1
      }
    }
    repeat(u16(4)) {
      skipName()
      at += 4
    }
    val found = mutableListOf<InetAddress>()
    repeat(u16(6)) {
      if (at >= length) return found
      skipName()
      if (at + 10 > length) return found
      val type = u16(at)
      val size = u16(at + 8)
      at += 10
      if (at + size > length) return found
      if ((type == TYPE_A && size == 4) || (type == TYPE_AAAA && size == 16)) {
        found.add(InetAddress.getByAddress(host, b.copyOfRange(at, at + size)))
      }
      at += size
    }
    return found
  }
}

/** React Native's usual client (cookies, cache, no timeouts) with \`TailnetDns\`. */
class TailnetDnsClientFactory(private val context: Context) : OkHttpClientFactory {
  override fun createNewNetworkModuleClient(): OkHttpClient =
    OkHttpClientProvider.createClientBuilder(context).dns(TailnetDns).build()
}
`;

/** MainApplication.kt with the factory set before React Native starts (right after `super.onCreate()`). */
function withFactory(source) {
  if (source.includes(MARK)) return source;
  const start = /override fun onCreate\(\) \{\s*\n(\s*)super\.onCreate\(\)\n/;
  const match = start.exec(source);
  if (!match) throw new Error("with-tailnet-dns: no `super.onCreate()` in MainApplication's onCreate");
  const indent = match[1];
  const line =
    `${indent}${MARK}\n` +
    `${indent}com.facebook.react.modules.network.OkHttpClientProvider.setOkHttpClientFactory(` +
    "TailnetDnsClientFactory(applicationContext))\n";
  return source.replace(start, (whole) => `${whole}${line}`);
}

module.exports = (config) => {
  const pkg = config.android?.package;
  if (!pkg) throw new Error("with-tailnet-dns: android.package is not set");
  config = withDangerousMod(config, [
    "android",
    (cfg) => {
      const dir = path.join(cfg.modRequest.platformProjectRoot, "app/src/main/java", ...pkg.split("."));
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, "TailnetDns.kt"), kotlinSource(pkg));
      return cfg;
    },
  ]);
  return withMainApplication(config, (cfg) => {
    if (cfg.modResults.language !== "kt") throw new Error("with-tailnet-dns: expected a Kotlin MainApplication");
    cfg.modResults.contents = withFactory(cfg.modResults.contents);
    return cfg;
  });
};

module.exports.withFactory = withFactory;
module.exports.kotlinSource = kotlinSource;
